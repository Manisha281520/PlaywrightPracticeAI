// CHAINED — full CRUD flow
// ─────────────────────────────────────────────────

test.describe('Users API — full CRUD flow', () => {

  test('create then read then update then delete', async ({ request }) => {

    // Step 1 — CREATE
    const createResponse = await ApiHelper.createUser(request, apiUsers.newUser)
    expect(createResponse.status()).toBe(201)
    const created = await ApiHelper.parseBody(createResponse)
    expect(created.id).toBeTruthy()

    const userId = created.id
    // save id to use in next steps

    // Step 2 — READ (jsonplaceholder does not persist but pattern is correct)
    const getResponse = await ApiHelper.getUser(request, 1)
    expect(getResponse.status()).toBe(200)
    const fetched = await ApiHelper.parseBody(getResponse)
    expect(fetched.id).toBe(1)

    // Step 3 — UPDATE
    const updateResponse = await ApiHelper.updateUser(request, 1, apiUsers.updatedUser)
    expect(updateResponse.status()).toBe(200)
    const updated = await ApiHelper.parseBody(updateResponse)
    expect(updated.name).toBe(apiUsers.updatedUser.name)

    // Step 4 — DELETE
    const deleteResponse = await ApiHelper.deleteUser(request, 1)
    expect(deleteResponse.status()).toBe(200)

  })

})
