// tests/api.spec.js
// PURPOSE: API tests using jsonplaceholder.typicode.com
//
// HOW THIS CONNECTS:
//   request fixture comes from Playwright automatically
//   baseURL set to API_BASE_URL in playwright.config.js
//   ApiHelper centralises all API calls
//   apiUsers provides test data

const { test, expect } = require('@playwright/test')
const { ApiHelper } = require('../helpers/ApiHelper')
const { apiUsers } = require('../data/users')

// ─────────────────────────────────────────────────
// READ — GET requests
// ─────────────────────────────────────────────────

test.describe('Users API — GET', () => {

  test('GET all users returns 200 and array', async ({ request }) => {
    const response = await ApiHelper.getAllUsers(request)

    // status check first — always
    expect(response.status()).toBe(200)

    const body = await ApiHelper.parseBody(response)

    // schema validation
    expect(Array.isArray(body)).toBe(true)
    expect(body.length).toBeGreaterThan(0)

    // check first item has required fields
    const firstUser = body[0]
    expect(typeof firstUser.id).toBe('number')
    expect(typeof firstUser.name).toBe('string')
    expect(typeof firstUser.email).toBe('string')
    expect(firstUser.name).toBeTruthy()
  })

  test('GET user by valid id returns correct user', async ({ request }) => {
    const response = await ApiHelper.getUser(request, 1)

    expect(response.status()).toBe(200)

    const body = await ApiHelper.parseBody(response)

    // value validation
    expect(body.id).toBe(1)
    expect(typeof body.name).toBe('string')
    expect(body.name).toBeTruthy()
    expect(typeof body.email).toBe('string')

    // nested object validation
    expect(typeof body.address).toBe('object')
    expect(body.address).toBeTruthy()           // catch null
    expect(typeof body.address.city).toBe('string')
  })

  test('GET user with invalid id returns 404', async ({ request }) => {
    const response = await ApiHelper.getUser(request, 99999)
    expect(response.status()).toBe(404)
  })

})

// ─────────────────────────────────────────────────
// CREATE — POST requests
// ─────────────────────────────────────────────────

test.describe('Users API — POST', () => {

  test('POST create user with valid data returns 201', async ({ request }) => {
    const response = await ApiHelper.createUser(request, apiUsers.newUser)

    expect(response.status()).toBe(201)

    const body = await ApiHelper.parseBody(response)

    // id was generated by server
    expect(body.id).toBeTruthy()

    // values match what we sent
    expect(body.name).toBe(apiUsers.newUser.name)
    expect(body.email).toBe(apiUsers.newUser.email)
  })

  test('POST create user response has correct schema', async ({ request }) => {
    const response = await ApiHelper.createUser(request, apiUsers.newUser)

    expect(response.status()).toBe(201)

    const body = await ApiHelper.parseBody(response)

    // schema validation — types
    expect(typeof body.id).toBe('number')
    expect(typeof body.name).toBe('string')
    expect(typeof body.email).toBe('string')
  })

})

// ─────────────────────────────────────────────────
// UPDATE — PUT requests
// ─────────────────────────────────────────────────

test.describe('Users API — PUT', () => {

  test('PUT update user returns 200 with updated data', async ({ request }) => {
    const response = await ApiHelper.updateUser(request, 1, apiUsers.updatedUser)

    expect(response.status()).toBe(200)

    const body = await ApiHelper.parseBody(response)

    // updated fields match what we sent
    expect(body.name).toBe(apiUsers.updatedUser.name)
    expect(body.email).toBe(apiUsers.updatedUser.email)
  })

})

// ─────────────────────────────────────────────────
